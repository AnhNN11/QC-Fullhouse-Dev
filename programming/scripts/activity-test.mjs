import assert from "node:assert/strict";
import fs from "node:fs";
import ts from "typescript";
import vm from "node:vm";
// Load our pure TypeScript date helpers only; never learner-submitted code.
const context={exports:{},Intl,Date,Set};
vm.runInNewContext(ts.transpileModule(fs.readFileSync("lib/activity.ts","utf8"),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,context);
const {learningDay,activitySummary}=context.exports;
assert.equal(learningDay(new Date("2026-09-22T18:00:00Z")),"2026-09-23");
let summary=activitySummary([],new Date("2026-09-23T03:00:00Z"));
assert.equal(summary.streak,0);assert.equal(summary.bestStreak,0);
summary=activitySummary(["2026-09-21","2026-09-22","2026-09-22","2026-09-23","2026-09-25"],new Date("2026-09-23T03:00:00Z"));
assert.equal(summary.streak,3);assert.equal(summary.bestStreak,3);assert.equal(summary.weeklyActivity.join(","),"1,1,1,0,0,0,0");
summary=activitySummary(["2024-02-28","2024-02-29"],new Date("2024-03-01T03:00:00Z"));
assert.equal(summary.streak,2);assert.equal(summary.learningDays.length,0);
summary=activitySummary(["2025-12-30","2025-12-31","2026-01-01"],new Date("2026-01-01T03:00:00Z"));
assert.equal(summary.streak,3);assert.equal(summary.learningDays.join(","),"1");
summary=activitySummary(["2026-09-19","2026-09-20"],new Date("2026-09-23T03:00:00Z"));
assert.equal(summary.streak,0);assert.equal(summary.bestStreak,2);
console.log("PASS: timezone, duplicate dates, future dates, streak gaps, leap day, year boundary and weekly activity.");
